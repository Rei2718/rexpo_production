INSERT INTO public.search_index (event_public_id, content)
SELECT
  event_public_id,
  (
    name || ' ' || 
    COALESCE(caption, '') || ' ' || 
    COALESCE(description, '') || ' ' || 
    COALESCE((
      SELECT string_agg(p->>'name', ' ') 
      FROM jsonb_array_elements(performers) AS p
    ), '') || ' ' ||
    COALESCE(organization->>'name', '')
  ) as content
FROM mv_event_details
ON CONFLICT DO NOTHING;